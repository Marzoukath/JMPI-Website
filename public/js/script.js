// Current language
let currentLanguage = "fr"

// Bootstrap Modal
const bootstrap = {
  Modal: (element) => {
    element.style.display = "block"
  },
}

// Initialize the website
document.addEventListener("DOMContentLoaded", () => {
  // Smooth scrolling for anchor links
  document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
    anchor.addEventListener("click", function (e) {
      e.preventDefault()
      const target = document.querySelector(this.getAttribute("href"))
      if (target) {
        target.scrollIntoView({
          behavior: "smooth",
          block: "start",
        })
      }
    })
  })

  // Navbar scroll effect
  window.addEventListener("scroll", () => {
    const navbar = document.querySelector(".custom-navbar")
    if (window.scrollY > 50) {
      navbar.classList.add("scrolled")
    } else {
      navbar.classList.remove("scrolled")
    }
  })

  // Scroll indicator click
  const scrollIndicator = document.querySelector(".scroll-indicator")
  if (scrollIndicator) {
    scrollIndicator.addEventListener("click", () => {
      const nextSection = document.querySelector("#presentation")
      if (nextSection) {
        nextSection.scrollIntoView({
          behavior: "smooth",
        })
      }
    })
  }

  // Contact form submission
  const contactForm = document.querySelector(".contact-form")
  if (contactForm) {
    contactForm.addEventListener("submit", function (e) {
      e.preventDefault()
      alert(translations[currentLanguage]["send"] + " - Message envoyé avec succès!")
      this.reset()
    })
  }

  // Initialize language
  updateLanguage()
})

// Language change function
function changeLanguage(lang) {
  currentLanguage = lang
  document.getElementById("current-lang").textContent = lang.toUpperCase()

  // Update document direction for Arabic
  if (lang === "ar") {
    document.documentElement.setAttribute("dir", "rtl")
    document.documentElement.setAttribute("lang", "ar")
  } else {
    document.documentElement.setAttribute("dir", "ltr")
    document.documentElement.setAttribute("lang", lang)
  }

  updateLanguage()
}

// Update language function
function updateLanguage() {
  const elements = document.querySelectorAll("[data-key]")
  elements.forEach((element) => {
    const key = element.getAttribute("data-key")
    if (translations[currentLanguage] && translations[currentLanguage][key]) {
      element.textContent = translations[currentLanguage][key]
    }
  })

  // Update placeholders
  const placeholderElements = document.querySelectorAll("[data-key-placeholder]")
  placeholderElements.forEach((element) => {
    const key = element.getAttribute("data-key-placeholder")
    if (translations[currentLanguage] && translations[currentLanguage][key]) {
      element.setAttribute("placeholder", translations[currentLanguage][key])
    }
  })
}

// Open event detail modal
function openEventDetail(eventId) {
  const event = eventData[eventId]
  if (!event) return

  // Update modal content
  document.getElementById("eventModalTitle").textContent = event.title
  document.getElementById("eventDate").textContent = event.date
  document.getElementById("eventTime").textContent = event.time
  document.getElementById("eventLocation").textContent = event.location
  document.getElementById("eventDescription").textContent = event.description

  // Update committee list
  const committeeList = document.getElementById("committeeList")
  committeeList.innerHTML = ""
  event.committee.forEach((member) => {
    const li = document.createElement("li")
    li.textContent = member
    committeeList.appendChild(li)
  })

  // Show modal
  const modal = new bootstrap.Modal(document.getElementById("eventModal"))
  modal.show()
}

// Animation on scroll
function animateOnScroll() {
  const elements = document.querySelectorAll(".stat-item, .team-card, .event-card")

  elements.forEach((element) => {
    const elementTop = element.getBoundingClientRect().top
    const elementVisible = 150

    if (elementTop < window.innerHeight - elementVisible) {
      element.style.opacity = "1"
      element.style.transform = "translateY(0)"
    }
  })
}

// Initialize animations
window.addEventListener("scroll", animateOnScroll)

// Counter animation for stats
function animateCounters() {
  const counters = document.querySelectorAll(".stat-number")

  counters.forEach((counter) => {
    const target = Number.parseInt(counter.textContent.replace("+", ""))
    const increment = target / 100
    let current = 0

    const timer = setInterval(() => {
      current += increment
      if (current >= target) {
        counter.textContent = target + "+"
        clearInterval(timer)
      } else {
        counter.textContent = Math.floor(current) + "+"
      }
    }, 20)
  })
}

// Trigger counter animation when stats section is visible
const statsSection = document.querySelector(".stats-container")
if (statsSection) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        animateCounters()
        observer.unobserve(entry.target)
      }
    })
  })

  observer.observe(statsSection)
}
